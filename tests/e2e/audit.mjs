import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.AUDIT_BASE_URL || 'http://127.0.0.1:4350';
const output = process.env.AUDIT_ARTIFACTS || '/tmp/radaros-audit-checks';
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, ...(process.env.AUDIT_USER ? { httpCredentials: { username: process.env.AUDIT_USER, password: process.env.AUDIT_PASSWORD } } : {}) });
const page = await context.newPage();
const errors = []; page.on('pageerror', error => errors.push(error.message));
const results = [];
try {
  const response = await page.goto(origin + '/wip', { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200);
  assert.equal(await page.locator('details[id^="R"]').count(), 30);
  assert.equal(await page.locator('details[id^="F"]').count(), 5);
  assert.equal(await page.locator('a').filter({ hasText: 'Ouvrir le board Forgejo' }).count(), 1);
  results.push('30 sections + 5 fondations et lien board présents');
  await page.getByLabel('Priorité', { exact: true }).selectOption('P0');
  assert.equal(await page.locator('details[id^="R"]').count(), 5);
  await page.getByLabel('Rechercher').fill('Shopify');
  assert.equal(await page.locator('details[id^="R"]').count(), 0);
  await page.getByRole('button', { name: 'Réinitialiser les filtres' }).click();
  await page.getByLabel('Rechercher').fill('Shopify');
  assert.equal(await page.locator('details[id^="R"]').count(), 5);
  await page.getByLabel('Rechercher').fill('');
  await page.getByLabel('Couverture', { exact: true }).selectOption('missing');
  assert.equal(await page.locator('details[id^="R"]').count(), 14);
  await page.getByLabel('Couverture', { exact: true }).selectOption('all');
  await page.getByRole('button', { name: 'Tout déplier', exact: true }).click();
  assert.equal(await page.locator('details[id^="R"][open]').count(), 30);
  await page.locator('#R01 summary').click();
  assert.equal(await page.locator('#R01').getAttribute('open'), null);
  await page.locator('#R01 summary').focus();
  await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#R01').open);
  assert.equal(await page.locator('details[id^="R"][open]').count(), 30);
  await page.getByRole('button', { name: 'Tout replier', exact: true }).click();
  assert.equal(await page.locator('details[id^="R"][open]').count(), 0);
  results.push('Recherche, filtres combinés, état vide, reset, ouverture globale et clavier vérifiés');
  assert.equal(await page.locator('#execution').count(), 1);
  assert.ok((await page.locator('#execution').innerText()).includes('gpt-6-astra'));
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exporter le listing' }).click();
  const download = await downloadEvent;
  const markdownPath = path.join(output, download.suggestedFilename());
  await download.saveAs(markdownPath);
  const markdown = await fs.readFile(markdownPath, 'utf8');
  assert.equal((markdown.match(/^## R\d\d —/gm) || []).length, 30);
  assert.equal((markdown.match(/^### F\d\d —/gm) || []).length, 5);
  assert.equal((markdown.match(/Ticket : https:\/\/git\.oratelecom\.net/g) || []).length, 35);
  assert.ok(markdown.includes('Arbitrages ouverts'));
  assert.ok(!markdown.includes('Ticket : à publier'));
  results.push('Export Markdown : 30 besoins, 5 fondations, 35 tickets, relecture et arbitrages');
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(output, 'wip-desktop.png') });
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Overflow at ${width}`);
  }
  await page.screenshot({ path: path.join(output, 'wip-mobile.png') });
  results.push('Affichage 1440 px et 390 px sans débordement horizontal');
  await page.goto(origin + '/tests', { waitUntil: 'networkidle' });
  assert.equal(await page.getByRole('heading', { name: 'Page de validation', exact: true }).count(), 1);
  assert.equal(await page.getByRole('heading', { name: 'Suivi RadarOS V2 · /wip', exact: true }).count(), 1);
  assert.equal(await page.locator('#security').count(), 1);
  assert.equal(await page.locator('#security article').count(), 6);
  assert.ok((await page.locator('#security').innerText()).includes('Connexion et paiement réels'));
  assert.equal(errors.length, 0, errors.join('\n'));
  results.push('/tests centralisée présente, aucune erreur JavaScript');
  await fs.writeFile(path.join(output, 'browser-results.json'), JSON.stringify({ origin, results, errors, checkedAt: new Date().toISOString() }, null, 2));
  console.log(JSON.stringify({ passed: results.length, results }, null, 2));
} finally { await browser.close(); }
